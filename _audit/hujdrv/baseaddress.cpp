#include "baseaddress.h"

NTSTATUS BaseAddress::GetBaseAddress(BaseAddressStruct x) {
	if (!x->process_id)
		return STATUS_UNSUCCESSFUL;

	PEPROCESS process = NULL;
	spuf(PsLookupProcessByProcessId)((HANDLE)x->process_id, &process);
	if (!process)
		return STATUS_UNSUCCESSFUL;

	ULONGLONG image_base = (ULONGLONG)spuf(PsGetProcessSectionBaseAddress)(process);
	if (!image_base) {
		ObDereferenceObject(process);
		return STATUS_UNSUCCESSFUL;
	}

	RtlCopyMemory(x->address, &image_base, sizeof(image_base));
	ObDereferenceObject(process);

	return STATUS_SUCCESS;
}

